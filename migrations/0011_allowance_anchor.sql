-- 订阅赠额的周期锚点。
--
-- 赠额按"每满一个自然月"刷新，锚点决定这个人的刷新日是几号。它在**首次成为付费
-- 会员**的那一刻由 /internal/sync-plan 固化，之后连续续费不动它——包月和包年都以它
-- 为起点按自然月切窗口，包年不预发全年。
--
-- ## 为什么必须存下来，而不是每次现算
--
-- 锚点一旦会漂，周期区间跟着漂，而赠额是按 (user, source, period_start) 去重的：
-- 换一个锚点就等于开出"新的一期"，用户凭空多拿一份额度。所以它必须是一个写定一次、
-- 之后只读的值，不能从别处（订阅表、计费中心、账号创建时间）每次推导——那些来源
-- 要么会变、要么在某些用户身上根本不存在。
--
-- 0 = 还没设过（不是会员，或者从没成为过会员）。此时不发赠额。
--
-- ## 中断之后重新订阅
--
-- 会员断掉时 sync-plan 会把它清回 0，重新订阅时再设一次。所以"连续续费保持锚点、
-- 中断后重新设锚点"这条规则完全由这一个字段的生命周期表达，不需要额外的状态位。
